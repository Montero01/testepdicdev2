begin;
set local statement_timeout='30s';
set local lock_timeout='3s';
set local plpgsql.check_asserts=on;
set local role authenticated;
do $test$
declare pcp uuid;rod uuid;admin_id uuid;waste_id uuid:=gen_random_uuid();daily_id uuid:=gen_random_uuid();r jsonb;dash jsonb;begin
 select id into pcp from profiles where lower(trim(position))='pcp'order by full_name limit 1;
 select id into rod from profiles where full_name='Rodrigo F. L. Campos';
 select id into admin_id from profiles where is_master order by full_name limit 1;
 assert pcp is not null and rod is not null and admin_id is not null;
 perform set_config('request.jwt.claim.sub',rod::text,true);
 assert pdi_performance_private.can_record_pcp_waste();
 r:=public.pdi_pcp_waste_save(pcp,pdi_performance_private.today_manaus(),5,waste_id,null,'Lista de reposições: pedido 999000001');
 assert r->>'entry_id'is null,'Desperdício não cria resultado diário fictício';
 assert(r->>'id')::uuid=waste_id;
 assert(r->>'created_by')::uuid=rod;
 r:=public.pdi_pcp_waste_save(pcp,pdi_performance_private.today_manaus(),5,waste_id,null,'Lista de reposições: pedido 999000001');
 assert(r->>'already_saved')::boolean,'Reenvio idempotente';
 dash:=public.pdi_pcp_dashboard(pdi_performance_private.today_manaus(),pdi_performance_private.today_manaus(),pcp);
 assert(dash->>'total_wasted')::numeric=5;
 assert dash->>'total_analyzed'is null and dash->>'utilization_percent'is null;
 assert(dash->>'pending_count')::int=1;
 assert jsonb_array_length(public.pdi_pcp_waste_entries(pdi_performance_private.today_manaus(),pdi_performance_private.today_manaus(),pcp,0)->'rows')=1;
 r:=public.pdi_pcp_waste_save(pcp,pdi_performance_private.today_manaus(),6,waste_id,1,'Correção da conferência da reposição');
 assert(r->>'revision')::int=2;assert r->>'notes'='Lista de reposições: pedido 999000001','Observação não é substituída pela justificativa de correção';
 begin perform public.pdi_pcp_waste_save(pcp,pdi_performance_private.today_manaus(),7,waste_id,1,'Revisão obsoleta precisa ser recusada');raise exception 'Aceitou revisão antiga';exception when serialization_failure then null;end;
 begin perform public.pdi_pcp_waste_save(pcp,pdi_performance_private.today_manaus()+1,1,null,null,null);raise exception 'Aceitou futuro';exception when invalid_parameter_value then null;end;
 perform set_config('request.jwt.claim.sub',pcp::text,true);
 begin perform public.pdi_pcp_waste_save(pcp,pdi_performance_private.today_manaus(),7,waste_id,2,'PCP não pode informar desperdício');raise exception 'PCP lançou desperdício';exception when insufficient_privilege then null;end;
 begin insert into pdi_pcp_daily(id,pcp_id,work_date,m2_saved,m2_analyzed,order_numbers)values(daily_id,pcp,pdi_performance_private.today_manaus(),0,1,array['999000001']);raise exception 'Análise não comportou desperdício pendente';exception when invalid_parameter_value then null;end;
 insert into pdi_pcp_daily(id,pcp_id,work_date,m2_saved,m2_analyzed,order_numbers)values(daily_id,pcp,pdi_performance_private.today_manaus(),1,10,array['999000001']);
 assert exists(select 1 from pdi_pcp_waste where id=waste_id and entry_id=daily_id and revision=3 and created_by=rod),'Vínculo preserva autoria original';
 perform set_config('request.jwt.claim.sub',rod::text,true);
 dash:=public.pdi_pcp_dashboard(pdi_performance_private.today_manaus(),pdi_performance_private.today_manaus(),pcp);
 assert(dash->>'entry_count')::int=1,'Sem contar o mesmo dia duas vezes';
 assert(dash->>'total_wasted')::numeric=6 and(dash->>'total_analyzed')::numeric=10;
 assert(dash->>'utilization_percent')::numeric=40;
 begin perform public.pdi_pcp_waste_save(pcp,pdi_performance_private.today_manaus(),10,waste_id,3,'Desperdício excede o analisado e salvo');raise exception 'Aceitou desperdício incompatível';exception when invalid_parameter_value then null;end;
 r:=public.pdi_pcp_waste_save(pcp,pdi_performance_private.today_manaus(),0,waste_id,3,'Conferência confirmou que não houve perda');assert(r->>'m2_wasted')::numeric=0;
 perform set_config('request.jwt.claim.sub',admin_id::text,true);
 assert exists(select 1 from pdi_performance_events where actor_id=rod and after_data->>'id'=waste_id::text),'Autoria nos logs';
 perform public.pdi_delete_performance('pcp_m2','daily',daily_id,'Anulação temporária do teste integrado');
 assert not exists(select 1 from pdi_pcp_waste where id=waste_id),'Excluir diário anula desperdício vinculado';
end$test$;
select 'PASS: independente, autoria, revisão, zero, bloqueios, vínculo automático, métricas sem duplicação e exclusão em cascata' resultado;
rollback;
